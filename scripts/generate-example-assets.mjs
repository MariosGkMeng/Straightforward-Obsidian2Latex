// Embeds example/ (as committed in git HEAD) into a generated TS module, so
// the plugin can write out a working demo vault (equation/figure/table
// blocks, an example note exercising every conversion feature) via the
// "Generate example" settings button — without needing the rest of the repo
// to be present, for the same reason python-assets.generated.ts exists.
import { execFileSync } from "child_process";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const repoRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

const BINARY_EXTENSIONS = new Set([".png", ".jpg", ".jpeg"]);

const files = execFileSync("git", ["ls-files", "example/"], {
	cwd: repoRoot,
	encoding: "utf8",
})
	.split("\n")
	.map((f) => f.trim())
	.filter(Boolean);

if (files.length === 0) {
	throw new Error("generate-example-assets: no tracked files found under example/ — is this a git repo?");
}

const assets = {};
for (const file of files) {
	const relPath = file.slice("example/".length);
	const isBinary = BINARY_EXTENSIONS.has(path.extname(file).toLowerCase());
	const raw = execFileSync("git", ["show", `HEAD:${file}`], { cwd: repoRoot, maxBuffer: 1024 * 1024 * 50 });
	assets[relPath] = isBinary
		? { type: "base64", content: raw.toString("base64") }
		: { type: "text", content: raw.toString("utf8") };
}

const outPath = path.join(repoRoot, "example-assets.generated.ts");
const body = `// AUTO-GENERATED by scripts/generate-example-assets.mjs — do not edit by hand.
// Regenerated on every build from example/ as committed in git HEAD.
export interface ExampleAsset {
	type: "text" | "base64";
	content: string;
}
export const EXAMPLE_ASSETS: Record<string, ExampleAsset> = ${JSON.stringify(assets, null, 2)};
`;
fs.writeFileSync(outPath, body, "utf8");
console.log(`generate-example-assets: embedded ${files.length} files into example-assets.generated.ts`);
