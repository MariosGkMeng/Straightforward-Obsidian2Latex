// Embeds converter.py and src/ (as committed in git HEAD — never the raw
// working tree, which can carry local-only drift or private data) into a
// generated TS module, so the built plugin can write them out to its own
// install folder at runtime. Obsidian's plugin installer (community browser
// or BRAT) only ever fetches main.js/manifest.json from a GitHub release —
// it never pulls the rest of the repository — so without this, converter.py
// and src/ simply wouldn't exist wherever the plugin gets installed.
import { execFileSync } from "child_process";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const repoRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

// src/note_map.json is runtime-generated cache data the tool populates
// during use, not shipped source — it's handled separately (seeded once,
// never overwritten) and must not be embedded here.
const EXCLUDE = new Set(["src/note_map.json"]);

const files = execFileSync("git", ["ls-files", "converter.py", "src/"], {
	cwd: repoRoot,
	encoding: "utf8",
})
	.split("\n")
	.map((f) => f.trim())
	.filter((f) => f && !EXCLUDE.has(f));

if (files.length === 0) {
	throw new Error("generate-python-assets: no tracked files found under converter.py/src/ — is this a git repo?");
}

const assets = {};
for (const file of files) {
	assets[file] = execFileSync("git", ["show", `HEAD:${file}`], { cwd: repoRoot, encoding: "utf8" });
}

const outPath = path.join(repoRoot, "python-assets.generated.ts");
const body = `// AUTO-GENERATED by scripts/generate-python-assets.mjs — do not edit by hand.
// Regenerated on every build from converter.py/src/ as committed in git HEAD.
export const PYTHON_ASSETS: Record<string, string> = ${JSON.stringify(assets, null, 2)};
`;
fs.writeFileSync(outPath, body, "utf8");
console.log(`generate-python-assets: embedded ${files.length} files into python-assets.generated.ts`);
